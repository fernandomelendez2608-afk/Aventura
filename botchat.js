const norm = t => String(t || '').toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '');
// intención aproximada del mensaje de un jugador
const INTENTS = [
  ['insulto', /\b(idiota|tonto|estupido|inutil|basura|maldito|imbecil|mierda|cobarde|payaso|malo)\b/],
  ['amenaza', /\b(te voy a|voy a (atacar|matar|destruir|conquistar)|ataco|atacare|te mato|te destruire|cuidado|prepar(a|ate)|guerra)\b/],
  ['alianza', /\b(alianza|aliado|aliarnos|aliemonos|aliarse)\b/],
  ['paz', /\b(paz|tregua|pacto|no me ataques|amigos)\b/],
  ['gracias', /\b(gracias|thx|thanks)\b/],
  ['ayuda', /\b(ayuda|ayudame|auxilio|dame|presta|prestame|refuerzos|necesito)\b/],
  ['estado', /\b(como vas|como te va|que tal|como estas|que haces|que tal vas|va ganando|quien gana)\b/],
  ['hola', /\b(hola|buenas|hey|saludos|buenos dias|buenas tardes|buenas noches|ola)\b/],
];
function intent(text) {
  const t = norm(text);
  for (const [k, re] of INTENTS) if (re.test(t)) return k;
  return 'otro';
}
// ¿el mensaje se dirige a este bot? (por su nombre, sin el prefijo «Bot»)
function addressed(text, botName) {
  const t = norm(text), n = norm(botName).replace(/^bot\s+/, '').trim();
  if (n && t.includes(n)) return true;
  const first = n.split(/\s+/)[0];
  return !!first && first.length >= 3 && new RegExp('(^|[^a-z])' + first.replace(/[^a-z0-9]/g, '') + '([^a-z]|$)').test(t);
}
const mentionsBots = text => /\b(bots?|robots?)\b/.test(norm(text));
function line(pers, key, r, vars) {
  const tbl = PHRASES[pers] || PHRASES.equilibrado, arr = tbl[key] || tbl.otro;
  const s = arr[Math.floor(r() * arr.length) % arr.length];
  return s.replace(/\{(\w)\}/g, (_, k) => (vars && vars[k] !== undefined ? vars[k] : ''));
}

module.exports = { PHRASES, intent, addressed, mentionsBots, line };
