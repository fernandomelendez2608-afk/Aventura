const { spawn } = require('child_process');
const fs = require('fs');
const wait = ms => new Promise(r => setTimeout(r, ms));
const srv = spawn('node', ['server.js'], { env: { ...process.env, PORT: '3117', DATA_DIR: '/tmp/ada-cdp5-data' } });
srv.stderr.on('data', d => console.log('[srv-err]', String(d)));
const chrome = spawn('google-chrome', ['--headless=new', '--no-sandbox', '--disable-gpu', '--no-proxy-server', '--remote-debugging-port=9337', '--user-data-dir=/tmp/ada-cdp5-chrome', 'about:blank'], { stdio: 'ignore' });
(async () => {
  await wait(2500);
  const targets = await (await fetch('http://127.0.0.1:9337/json')).json();
  const page = targets.find(t => t.type === 'page');
  const ws = new WebSocket(page.webSocketDebuggerUrl); await new Promise(r => ws.onopen = r);
  let id = 0; const pend = new Map(); const errs = [];
  ws.onmessage = e => { const m = JSON.parse(e.data); if (m.id && pend.has(m.id)) { pend.get(m.id)(m); pend.delete(m.id); } else if (m.method === 'Runtime.exceptionThrown') errs.push(m.params.exceptionDetails.text + ' ' + (m.params.exceptionDetails.exception?.description || '')); };
  const cdp = (method, params = {}) => new Promise(r => { const i = ++id; pend.set(i, r); ws.send(JSON.stringify({ id: i, method, params })); });
  const ev = async expr => { const r = await cdp('Runtime.evaluate', { expression: expr, awaitPromise: true, returnByValue: true }); return r.result.result.value; };
  fs.mkdirSync('/tmp/shots', { recursive: true });
  const shot = async name => { const r = await cdp('Page.captureScreenshot', { format: 'png' }); fs.writeFileSync('/tmp/shots/' + name + '.png', Buffer.from(r.result.data, 'base64')); };
  await cdp('Runtime.enable'); await cdp('Page.enable');
  await cdp('Emulation.setDeviceMetricsOverride', { width: 390, height: 780, deviceScaleFactor: 2, mobile: true });
  await cdp('Page.navigate', { url: 'http://127.0.0.1:3117/' }); await wait(1300);
  await ev(`document.getElementById('hName').value='Fercho'; document.getElementById('hCreate').click()`); await wait(700);
  await ev(`document.getElementById('lWorld').scrollIntoView()`); await wait(200);
  await shot('e1-lobby-mundo');
  const set = async (k, v) => { await ev(`(()=>{const s=document.getElementById('w_${k}'); s.value='${v}'; s.dispatchEvent(new Event('change'))})()`); await wait(300); };
  await set('mapSize', 'enorme'); await set('cities', 'abundantes'); await set('biome', 'desierto'); await set('fauna', 'agresiva');
  await set('startUnits', '14'); await set('startLevel', '6'); await set('startArmor', 'hierro');
  console.log('cfg en servidor:', await ev(`JSON.stringify(S.cfg)`));
  await ev(`document.getElementById('lBot').click()`); await wait(300);
  await ev(`document.getElementById('lStart').click()`); await wait(1500);
  console.log('estado:', await ev(`S.status`), '| mapa', await ev(`S.map && S.map.w`), '| unidades propias', await ev(`S.units.length`), '| nivel', await ev(`S.units[0].lv`));
  await shot('e2-juego-desierto');
  console.log('errores JS:', JSON.stringify(errs));
  chrome.kill(); srv.kill(); process.exit(errs.length ? 1 : 0);
})();
