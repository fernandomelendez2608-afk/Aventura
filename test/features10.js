'use strict';
require('./seed.js');
// Pruebas de: mordedura de vampiro (v1.52)
const E = require('../engine.js'), S = require('../shared.js');
let fails = 0;
const ok = (c, m) => { if (!c) { fails++; console.log('  ✗ ' + m); } else console.log('  ✓ ' + m); };
const mk = () => { const g = E.createGame('V', 'Host', 't'); E.addBot(g, 'azar'); E.startGame(g); g.creatures = []; return g; };
console.log('Vampirismo');
let g = mk(); const u = g.units.find(x => x.o === 0 && !x.sm), conde = E.spawnCreature(g, 'conde', u.x + 1, u.y, 10);
u.lv = 20; u.sk.dano = 10; const base = E.eff(g, u), chance0 = S.VAMP.chance;
S.VAMP.chance = 1; E.vampBite(g, conde, u);
ok(u.vamp === 1 && u.o === 0, 'la mordedura del Conde convierte a la unidad en vampiro y sigue siendo tuya');
const ev = E.eff(g, u);
ok(ev.dmg > base.dmg && ev.fx.vida >= 0.2 && ev.fx.regen >= 0.03, `gana ventaja racial (daño ${base.dmg}→${ev.dmg}, roba ${ev.fx.vida}, regen ${ev.fx.regen})`);
ok(g.events.some(l => /muerde a/.test(l.text)), 'se avisa en el registro');
ok(E.snapshot(g, 0).mine.find(x => x.id === u.id).vp === 1, 'la vista marca al vampiro (vp)');
const du = JSON.parse(E.serialize ? JSON.stringify(E.deserialize(E.serialize(g)).units.find(x => x.id === u.id).vamp) : '1'); ok(du === 1, 'el vampirismo se guarda con la partida');
console.log('Quién se contagia');
g = mk(); const v = g.units.find(x => x.o === 0 && !x.sm), wolf = E.spawnCreature(g, 'lobo', v.x + 1, v.y, 10); E.vampBite(g, wolf, v); ok(!v.vamp, 'un lobo no contagia');
const cd = E.spawnCreature(g, 'conde', v.x + 1, v.y, 10); S.VAMP.chance = 0; E.vampBite(g, cd, v); ok(!v.vamp, 'con probabilidad 0 nunca se contagia');
S.VAMP.chance = 1; const cart = { id: 999, o: 0, x: v.x, y: v.y, cart: 1, hp: 10, inv: { m: {}, it: [] }, eq: {}, sk: {} }; E.vampBite(g, cd, cart); ok(!cart.vamp, 'las carretas y unidades auxiliares no se contagian');
const city = g.cities.find(c => c.owner === 0 && c.cap); city.b = Object.assign(city.b || {}, { iglesia: 1 }); v.x = city.x; v.y = city.y; E.vampBite(g, cd, v); ok(v.vamp === 1, 'una iglesia de nivel 1 no basta para protegerse');
delete v.vamp; city.b.iglesia = 2; E.vampBite(g, cd, v); ok(!v.vamp, 'una iglesia de nivel 2 cerca protege del contagio');
console.log('Purificar');
city.b.iglesia = 1; v.vamp = 1; city.st.m = {}; let r = E.cmd(g, 0, { a: 'purify', u: v.id }); ok(!!r.err && v.vamp === 1, 'sin almas en el almacén no se puede purificar');
city.st.m = { alma: 5 }; r = E.cmd(g, 0, { a: 'purify', u: v.id }); ok(!r.err && !v.vamp && city.st.m.alma < 5, 'con iglesia y almas se purifica y cuesta almas');
r = E.cmd(g, 0, { a: 'purify', u: v.id }); ok(!!r.err, 'una unidad sana no se purifica');
v.vamp = 1; v.x = city.x + 8; v.y = city.y + 8; r = E.cmd(g, 0, { a: 'purify', u: v.id }); ok(!!r.err && v.vamp === 1, 'lejos de la iglesia no se puede purificar');
S.VAMP.chance = chance0;
console.log(fails ? `\n${fails} fallos` : '\nTodo bien');
process.exit(fails ? 1 : 0);
