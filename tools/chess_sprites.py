ORDER = "PNBRQK"
PAL = {
    "w": dict(fill=(244, 240, 228), shade=(184, 178, 160), light=(255, 255, 255)),
    "b": dict(fill=(62, 66, 92), shade=(32, 34, 56), light=(110, 118, 160)),
}
OUT = (14, 14, 20)


def piece(name, side):
    rows = [r for r in ART[name].strip("\n").split("\n")]
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), name
    if "X" in rows[0] and "X" not in rows[15]:
        rows = ["." * 16] + rows[:15]
    mask = [[ch == "X" for ch in r] for r in rows]
    pal = PAL[side]
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    g = lambda x, y: 0 <= x < 16 and 0 <= y < 16 and mask[y][x]
    for y in range(16):
        for x in range(16):
            if mask[y][x]:
                c = pal["fill"]
                if not g(x + 1, y) or not g(x + 2, y) and g(x + 1, y) and name != "N":
                    c = pal["shade"]
                if not g(x - 1, y) and g(x + 1, y):
                    c = pal["light"]
                im.putpixel((x, y), c + (255,))
    for y in range(16):
        for x in range(16):
            if not mask[y][x] and any(g(x + dx, y + dy) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                im.putpixel((x, y), OUT + (255,))
    return im


def main():
    sheet = Image.new("RGBA", (16 * 6, 32), (0, 0, 0, 0))
    for r, side in enumerate("wb"):
        for c, name in enumerate(ORDER):
            sheet.paste(piece(name, side), (c * 16, r * 16))
    here = os.path.dirname(os.path.abspath(__file__))
    sheet.save(os.path.join(here, "..", "static", "chess.png"), optimize=True)
    big = sheet.resize((sheet.width * 8, sheet.height * 8), Image.NEAREST)
    bg = Image.new("RGBA", big.size, (91, 140, 74, 255)); bg.alpha_composite(big)
    bg.save(os.path.join(os.environ.get("PREVIEW_DIR", here), "chess_preview.png"))


if __name__ == "__main__":
    main()
